"""Короткие машинные сообщения для интерфейса.

Сервер не знает, на каком языке открыто окно. Поэтому вместо готовой
русской фразы он отдаёт код и числа, а перевод делает интерфейс:

    {"c": "loop.saved", "n": 3, "got": 12, "total": 29}

Старые записи в базе -- обычный текст, интерфейс показывает их как есть.
"""
from __future__ import annotations

import json


def job_msg(code: str, **params: object) -> str:
    """Собрать сообщение задачи: код плюс подстановки."""
    return json.dumps({"c": code, **params}, ensure_ascii=False)
